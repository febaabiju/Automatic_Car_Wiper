-- 1. Create table for storing sensor readings and wiper telemetry
CREATE TABLE IF NOT EXISTS sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(50) NOT NULL,
    rain_value INTEGER NOT NULL CHECK (rain_value >= 0 AND rain_value <= 4095),
    rain_status VARCHAR(50) NOT NULL,
    wiper_on BOOLEAN NOT NULL,
    wiper_speed VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 2. Index for fast querying of historical telemetry and latest records
CREATE INDEX IF NOT EXISTS idx_sensor_readings_created_at 
ON sensor_readings (created_at DESC);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE sensor_readings ENABLE ROW LEVEL SECURITY;

-- 4. Remove all previous/legacy RLS policies
DROP POLICY IF EXISTS "Allow public read access" ON sensor_readings;
DROP POLICY IF EXISTS "Allow public insert access" ON sensor_readings;
DROP POLICY IF EXISTS "Allow read access to all" ON sensor_readings;
DROP POLICY IF EXISTS "Allow service_role insert only" ON sensor_readings;

-- ====================================================================
-- Security Architecture Notes:
-- ====================================================================
-- With Row Level Security (RLS) enabled and NO permissive policies defined:
-- - All direct public/anonymous ('anon') and authenticated client access
--   via the public Supabase PostgREST API is completely blocked by default.
-- - No external client can directly SELECT, INSERT, UPDATE, or DELETE records.
--
-- Server-Side Backend Access:
-- - The FastAPI backend accesses Supabase using the server-side secret key
--   (configured via SUPABASE_KEY in the backend .env file).
-- - In Supabase PostgreSQL, the service_role key automatically possesses the
--   BYPASSRLS attribute, allowing the FastAPI backend to securely insert telemetry
--   and retrieve readings while keeping the database shielded from the public internet.
-- ====================================================================
